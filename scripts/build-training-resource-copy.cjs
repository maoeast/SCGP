#!/usr/bin/env node

const fs = require('node:fs/promises')
const path = require('node:path')
const { createJiti } = require('jiti')

const REPO_ROOT = process.cwd()
const DEFAULT_CSV_PATH = path.join(
  REPO_ROOT,
  'docs',
  'references',
  'resource-copy',
  '2026-03-30-training-resource-copy.csv'
)
const DEFAULT_OUTPUT_PATH = path.join(
  REPO_ROOT,
  'src',
  'data',
  'generated-training-resource-copy.ts'
)

function parseArgs(argv) {
  const options = {
    csvPath: DEFAULT_CSV_PATH,
    outputPath: DEFAULT_OUTPUT_PATH,
  }

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]

    if (arg === '--csv') {
      options.csvPath = path.resolve(argv[index + 1] || '')
      index += 1
      continue
    }

    if (arg === '--out') {
      options.outputPath = path.resolve(argv[index + 1] || '')
      index += 1
      continue
    }

    if (arg === '--help' || arg === '-h') {
      printHelp()
      process.exit(0)
    }

    throw new Error(`未知参数: ${arg}`)
  }

  return options
}

function printHelp() {
  console.log(`
生成训练资源文案 override map

用途:
- 读取 docs/references/resource-copy/2026-03-30-training-resource-copy.csv
- 生成 src/data/generated-training-resource-copy.ts

用法:
  node scripts/build-training-resource-copy.cjs
  node scripts/build-training-resource-copy.cjs --csv <path> --out <path>
`.trim())
}

function escapeTsString(value) {
  return JSON.stringify(String(value || ''))
}

async function main() {
  const options = parseArgs(process.argv.slice(2))
  const jiti = createJiti(__filename, {
    alias: {
      '@': path.join(REPO_ROOT, 'src'),
    },
  })

  const {
    parseTrainingResourceCopyCsv,
    parseTrainingResourceCopyKey,
  } = jiti('../src/utils/training-resource-copy.ts')

  const csvContent = await fs.readFile(options.csvPath, 'utf8')
  const rows = parseTrainingResourceCopyCsv(csvContent)
  const seenKeys = new Set()

  for (const row of rows) {
    if (!row.resourceKey) {
      throw new Error('文案 CSV 存在空 resourceKey')
    }
    if (!row.name) {
      throw new Error(`文案 CSV 存在空 name: ${row.resourceKey}`)
    }
    if (!parseTrainingResourceCopyKey(row.resourceKey)) {
      throw new Error(`文案 CSV 包含未知 resourceKey: ${row.resourceKey}`)
    }
    if (seenKeys.has(row.resourceKey)) {
      throw new Error(`文案 CSV 存在重复 resourceKey: ${row.resourceKey}`)
    }
    seenKeys.add(row.resourceKey)
  }

  const rowLines = rows.map((row) => `  {
    resourceKey: ${escapeTsString(row.resourceKey)},
    origin: ${escapeTsString(row.origin)},
    moduleCode: ${escapeTsString(row.moduleCode)},
    resourceType: ${escapeTsString(row.resourceType)},
    name: ${escapeTsString(row.name)},
    description: ${escapeTsString(row.description)},
    previewDescription: ${escapeTsString(row.previewDescription)},
    repeatPlayHint: ${escapeTsString(row.repeatPlayHint)},
  },`)

  const fileContent = `import type { TrainingResourceCopyRow } from '@/utils/training-resource-copy'

// Generated from docs/references/resource-copy/2026-03-30-training-resource-copy.csv
// Do not edit this file manually.
export const TRAINING_RESOURCE_COPY_ROWS: TrainingResourceCopyRow[] = [
${rowLines.join('\n')}
]

const TRAINING_RESOURCE_COPY_MAP = new Map(
  TRAINING_RESOURCE_COPY_ROWS.map((row) => [row.resourceKey, row] as const)
)

export function getTrainingResourceCopyOverride(resourceKey: string): TrainingResourceCopyRow | null {
  return TRAINING_RESOURCE_COPY_MAP.get(resourceKey) || null
}
`

  await fs.writeFile(options.outputPath, fileContent, 'utf8')
  console.log(`[training-resource-copy] generated ${path.relative(REPO_ROOT, options.outputPath)} from ${path.relative(REPO_ROOT, options.csvPath)}`)
}

main().catch((error) => {
  console.error('[training-resource-copy] build failed:', error)
  process.exit(1)
})
